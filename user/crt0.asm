; ============================================================
; 用户程序的入口
;
;   _start 必须是 .entry 节里唯一的、也是最靠前的东西：
;   链接脚本把 .entry 排在映像最前面，LXE 头部里的 entry 偏移是 0，
;   加载器会直接跳到 USER_BASE。如果别的代码排在 _start 前面，
;   CPU 一上来就会执行到它（之前就因为这个把 ret 放在了最前面，
;   结果去读还没映射的栈顶，直接缺页）。
; ============================================================

[BITS 32]

section .entry code align=16

global _start
extern _main

_start:
    call _main              ; main 的返回值当作退出码
    mov ebx, eax
    xor eax, eax            ; SYS_EXIT = 0
    int 0x80

    ; exit 系统调用不会返回；万一返回了就停在这里
.hang:
    hlt
    jmp .hang

; ------------------------------------------------------------
; MinGW 的 GCC 在编译名为 main 的函数时会插入一个对 __main 的调用
; （本来用于跑 C++ 全局构造函数）。我们没有运行时，给个空实现就行。
;
; 注意下划线的个数：GCC 内部管这个钩子叫 __main，PE 目标又会给
; C 符号加一个前导下划线，所以目标文件里实际引用的是 ___main。
; 两个名字都定义，免得换个工具链版本就链接失败。
; ------------------------------------------------------------
section .text

global __main
global ___main

__main:
___main:
    ret
